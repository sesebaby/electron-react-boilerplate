-- ===============================================
-- 库存流水统计
-- ===============================================
SELECT '=== 库存流水统计 ===' as message;
SELECT
    CASE
        WHEN transaction_type = 'in' THEN '入库'
        WHEN transaction_type = 'out' THEN '出库'
        WHEN transaction_type = 'adjustment' THEN '调整'
        ELSE transaction_type
    END as transaction_name,
    COUNT(*) as transaction_count,
    SUM(quantity) as total_quantity,
    ROUND(SUM(total_amount), 2) as total_amount
FROM inventory_transactions
GROUP BY transaction_type;

-- ===============================================
-- 最近交易记录
-- ===============================================
SELECT '=== 最近10笔交易记录 ===' as message;
SELECT
    t.created_at,
    i.name as product_name,
    i.sku,
    CASE
        WHEN t.transaction_type = 'in' THEN '入库'
        WHEN t.transaction_type = 'out' THEN '出库'
        ELSE t.transaction_type
    END as transaction_type,
    t.quantity,
    t.unit_price,
    t.total_amount,
    t.notes
FROM inventory_transactions t
JOIN inventory_items i ON t.item_id = i.id
ORDER BY t.created_at DESC
LIMIT 10;

