-- ===============================================
-- 库存状态分析
-- ===============================================
SELECT '=== 库存状态分析 ===' as message;
SELECT
    CASE
        WHEN status = 'in-stock' THEN '正常库存'
        WHEN status = 'low-stock' THEN '库存预警'
        WHEN status = 'out-of-stock' THEN '缺货商品'
        ELSE status
    END as status_name,
    COUNT(*) as count,
    SUM(stock_quantity) as total_stock,
    ROUND(SUM(total_value), 2) as total_value
FROM inventory_items
GROUP BY status
ORDER BY
    CASE status
        WHEN 'in-stock' THEN 1
        WHEN 'low-stock' THEN 2
        WHEN 'out-of-stock' THEN 3
        ELSE 4
    END;

