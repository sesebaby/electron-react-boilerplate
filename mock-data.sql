-- 库存状态统计
-- ===============================================
SELECT '=== 库存状态统计 ===' as message;
SELECT 
    status,
    COUNT(*) as count,
    SUM(stock_quantity) as total_stock,
    SUM(total_value) as total_value
FROM inventory_items 
GROUP BY status;

-- ===============================================
-- 分类统计
-- ===============================================
SELECT '=== 分类统计 ===' as message;
SELECT 
    category,
    COUNT(*) as product_count,
    SUM(stock_quantity) as total_stock,
    ROUND(AVG(unit_price), 2) as avg_price
FROM inventory_items 
GROUP BY category;

-- ===============================================
-- 供应商统计
-- ===============================================
