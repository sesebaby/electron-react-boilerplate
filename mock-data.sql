    t.created_at,
    i.name as product_name,
    i.sku,
    t.transaction_type,
    t.quantity,
    t.unit_price,
    t.total_value,
    t.reason
FROM inventory_transactions t
JOIN inventory_items i ON t.item_id = i.id
ORDER BY t.created_at DESC
LIMIT 10;

