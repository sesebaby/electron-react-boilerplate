        WHEN type = 'time' THEN '时间单位'
        ELSE type
    END as unit_type_name,
    COUNT(*) as count,
    GROUP_CONCAT(symbol, ', ') as symbols
FROM units
WHERE is_active = 1
GROUP BY type
ORDER BY
    CASE type
        WHEN 'quantity' THEN 1
        WHEN 'weight' THEN 2
        WHEN 'length' THEN 3
        WHEN 'volume' THEN 4
        WHEN 'area' THEN 5
        WHEN 'time' THEN 6
        ELSE 7
    END;

